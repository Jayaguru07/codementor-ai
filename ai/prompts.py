def format_retrieved_context(retrieved_chunks: List[Dict[str, Any]]) -> str:
    """Formats a list of retrieved chunk dictionaries into a readable context block."""
    if not retrieved_chunks:
        return "No specific documents found in the local knowledge base."

    formatted_sections: List[str] = []
    for idx, chunk in enumerate(retrieved_chunks, 1):
        source = chunk.get("source", "unknown")
        text = chunk.get("text", "").strip()
        formatted_sections.append(
            f"--- Document [{idx}] (Source: {source}) ---\n{text}"
        )

    return "\n\n".join(formatted_sections)


def build_analysis_prompt(
    language: str,
    code: str,
    error_message: str = "",
    retrieved_chunks: Optional[List[Dict[str, Any]]] = None,
) -> str:
    """Assembles the complete user prompt incorporating RAG context and student inputs."""
    context_text = format_retrieved_context(retrieved_chunks or [])
    error_section = error_message.strip() if error_message and error_message.strip() else "None provided (Code review/explanation requested)."

    prompt = f"""RETRIEVED KNOWLEDGE BASE CONTEXT:
============================================================
{context_text}
============================================================

STUDENT SUBMISSION:
------------------------------------------------------------
Programming Language: {language}

Error Message / Problem:
{error_section}

Submitted Code:
```{language.lower()}
{code}
```
------------------------------------------------------------

Please analyze the student's code using the retrieved knowledge base context.
Identify the error or improvement areas, explain the root cause, provide corrected code,
and respond strictly in the required JSON format.
"""
    return prompt
