"""Prompt Templates and Pydantic Schemas for CodeMentor AI.

This module is responsible for:
1. Defining the structured output data models using Pydantic.
2. Formulating the system instructions for CodeMentor AI.
3. Assembling the RAG-augmented prompt containing student code, error context,
   and retrieved knowledge base documentation.

EDUCATIONAL NOTE FOR VIVA:
- Why Strict Structured JSON?
  In modern LLM applications, downstream services (like a web frontend or database)
  cannot reliably parse arbitrary conversational free text. By constraining the LLM
  to return valid JSON validated through a Pydantic schema, we guarantee that all
  required fields (explanation, cause, corrected code, etc.) are always present and correctly typed.
- Why RAG In Context?
  Rather than asking the LLM to rely solely on internal parametric memory, we inject
  retrieved reference documentation directly into the prompt. The LLM acts as an
  intelligent synthesis engine over our trusted knowledge base.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator


# -----------------------------------------------------------------------------
# Pydantic Schemas
# -----------------------------------------------------------------------------

class SourceItem(BaseModel):
    """Metadata for a retrieved knowledge chunk used in the analysis."""
    source: str = Field(..., description="File path of the knowledge document.")
    score: float = Field(..., description="Cosine similarity score.")


class CodeAnalysisResult(BaseModel):
    """Structured response model generated by CodeMentor AI."""
    error_type: str = Field(
        ...,
        description="The identified error category (e.g. IndexError, SyntaxError, LogicError).",
    )
    explanation: str = Field(
        ...,
        description="Clear, student-friendly explanation of what the error means.",
    )
    cause: str = Field(
        ...,
        description="The root cause of the error in the student's specific code.",
    )
    concept: str = Field(
        ...,
        description="The primary programming concept involved (e.g. Python List Indexing).",
    )
    corrected_code: str = Field(
        ...,
        description="The corrected version of the student's code.",
    )
    learning_tip: str = Field(
        ...,
        description="A practical debugging or coding tip to avoid this issue in the future.",
    )
    practice_question: str = Field(
        ...,
        description="One short, targeted practice question to reinforce understanding.",
    )
    sources: List[SourceItem] = Field(
        default_factory=list,
        description="List of knowledge base sources retrieved by RAG.",
    )


class CodeAnalysisRequest(BaseModel):
    """Input request model for code analysis (used by API and services)."""
    language: str = Field(..., description="Programming language of the code.")
    code: str = Field(..., description="Source code submitted by the student.")
    error_message: str = Field(
        default="",
        description="Optional compiler/runtime error message or problem description.",
    )

    @field_validator("language")
    @classmethod
    def validate_language(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Programming language must not be empty.")
        return v.strip()

    @field_validator("code")
    @classmethod
    def validate_code(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Code snippet must not be empty.")
        return v.strip()


